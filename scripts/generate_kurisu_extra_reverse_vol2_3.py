def vector(values: list[float], keys: tuple[str, ...]) -> dict[str, float]:
    if len(values) != len(keys):
        raise ValueError((len(values), len(keys)))
    return dict(zip(keys, (float(x) for x in values)))


def event(
    text: str,
    lines: list[int],
    stimulus: list[float],
    target: list[float],
    behavior: list[float],
    evidence: str,
    uncertainty: str = "具体强度为叙事证据基础上的标注估计。",
) -> dict:
    return {
        "text": text,
        "current_stimulus": vector(stimulus, EK),
        "emotion_target": vector(target, EK),
        "behavior_target": vector(behavior, BK),
        "_source_lines": lines,
        "_evidence_summary": evidence,
        "_uncertainty": uncertainty,
    }


def make_sequence(
    sequence_id: str,
    chapter: str,
    source_file: str,
    source_lines: tuple[int, int],
    context_note: str,
    events: list[dict],
) -> tuple[dict, dict]:
    history = vector([0] * 8, EK)
    output_events = []
    audit_events = []
    for index, item in enumerate(events):
        target = item["emotion_target"]
        output_events.append(
            {
                "text": item["text"],
                "historical_emotion": history.copy(),
                "current_stimulus": item["current_stimulus"],
                "emotion_target": target,
                "behavior_target": item["behavior_target"],
                "delta_seconds": 0.0 if index == 0 else 1.0,
            }
        )
        audit_events.append(
            {
                "event_index": index,
                "source_lines": item["_source_lines"],
                "evidence_summary": item["_evidence_summary"],
                "uncertainty": item["_uncertainty"],
                "timing_note": "原文无逐事件时间戳；本事件按序列连续事件使用占位间隔。",
            }
        )
        history = target.copy()
    record = {
        "sequence_id": sequence_id,
        "target_character": "牧濑红莉栖",
        "events": output_events,
    }
    audit = {
        "record_type": "included_sequence",
        "sequence_id": sequence_id,
        "target_character": "牧濑红莉栖",
        "source_file": source_file,
        "chapter": chapter,
        "source_lines": list(source_lines),
        "context_note": context_note,
        "events": audit_events,
        "timing_note": "原文无逐事件时间戳；首事件 delta_seconds=0.0，后续事件使用 1.0 秒占位；历史情绪按上一事件 emotion_target 继承。",
    }
    return record, audit


