def build_records() -> tuple[list[dict], list[dict]]:
    records: list[dict] = []
    audits: list[dict] = []
    for seq_id, label, seq_range, specs in SCENES:
        events = []
        audit_events = []
        previous = ZERO
        for index, spec in enumerate(specs):
            history = ZERO if index == 0 else previous
            item = {
                "text": spec["text"],
                "historical_emotion": history,
                "current_stimulus": spec["current_stimulus"],
                "emotion_target": spec["emotion_target"],
                "behavior_target": spec["behavior_target"],
                "delta_seconds": 0.0 if index == 0 else 1.0,
            }
            events.append(item)
            audit_events.append({
                "event_index": index,
                "source_lines": spec["source_lines"],
                "evidence_summary": spec["evidence_summary"],
                "evidence_level": spec["evidence_level"],
                "uncertainty": spec["uncertainty"],
            })
            previous = spec["emotion_target"]
        records.append({"sequence_id": seq_id, "target_character": "牧濑红莉栖", "events": events})
        audits.append({
            "record_type": "included_sequence",
            "sequence_id": seq_id,
            "target_character": "牧濑红莉栖",
            "source_file": SOURCE_NAME,
            "chapter": label,
            "source_lines": list(seq_range),
            "context_note": "连续场景；第一事件历史情绪按协议使用全零默认，后续事件继承上一事件 emotion_target。",
            "events": audit_events,
            "timing_note": "原文没有逐事件秒级时间戳；首事件 delta_seconds=0.0，其余连续事件使用 1.0 占位，不代表真实秒数。",
        })
    audits.append({
        "record_type": "coverage_review",
        "source_file": SOURCE_NAME,
        "chapter": "Reverse 全卷覆盖审查",
        "source_lines": [70, 6579],
        "covered_sequences": [
            {"sequence_id": seq_id, "source_lines": list(seq_range), "note": label}
            for seq_id, label, seq_range, _ in SCENES
        ],
        "excluded_ranges": [
            {"source_lines": [7, 69], "reason": "前置说明和广告内容，没有牧濑红莉栖直接事件。"},
            {"source_lines": [6552, 6579], "reason": "后记仅为作者说明，不进入角色训练数据。"},
        ],
        "decision": "included_selected_direct_scenes; excluded_non_character_and_afterword",
    })
    return records, audits


def main() -> None:
    records, audits = build_records()
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    data_path = OUT_DIR / "kurisu_extra_reverse_vol1_draft.jsonl"
    audit_path = OUT_DIR / "kurisu_extra_reverse_vol1_draft_audit.jsonl"
    data_path.write_text("".join(json.dumps(record, ensure_ascii=False, separators=(",", ":")) + "\n" for record in records), encoding="utf-8")
    audit_path.write_text("".join(json.dumps(record, ensure_ascii=False, separators=(",", ":")) + "\n" for record in audits), encoding="utf-8")
    print(f"wrote {data_path} ({len(records)} sequences, {sum(len(r['events']) for r in records)} events)")
    print(f"wrote {audit_path} ({len(audits)} records)")


if __name__ == "__main__":
    main()
